import { expect, test } from '@playwright/test';

test('all editable main-admin data survives save and page reload; failed writes report failure', async ({ page }) => {
  await page.goto('/admin/login');
  await page.getByRole('textbox', { name: 'Admin ID', exact: true }).fill('e2eadmin');
  await page.locator('input[name="password"]:visible').fill('E2e-only-password-2026');
  await page.getByRole('button', { name: 'Login to Dashboard' }).click();
  await expect(page).toHaveURL(/\/admin$/);
  const tab = async (name: string) => { await page.getByRole('button', { name, exact: true }).click(); };
  const modal = (save: string) => page.locator('.fixed:visible').filter({ has: page.getByRole('button', { name: save, exact: true }) });
  const reloadTab = async (name: string) => { await page.reload(); await tab(name); };

  await tab('Categories');
  await page.getByRole('button', { name: 'Add Category', exact: true }).click();
  let dialog = modal('Save');
  await dialog.locator('input').nth(0).fill('Persistence category');
  await dialog.locator('input').nth(1).fill('Original category description');
  await dialog.locator('input').nth(2).fill('/images/manjha/m01.png');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const categoryCard = page.locator('.card').filter({ has: page.getByText('Persistence category', { exact: true }) });
  await categoryCard.getByRole('button', { name: 'Edit', exact: true }).click();
  dialog = modal('Save');
  await dialog.locator('input').nth(1).fill('Saved category description');
  await dialog.locator('input').nth(2).fill('/images/manjha/m02.png');
  await dialog.getByLabel('Active', { exact: true }).uncheck();
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await reloadTab('Categories');
  await categoryCard.getByRole('button', { name: 'Edit', exact: true }).click();
  dialog = modal('Save');
  await expect(dialog.locator('input').nth(1)).toHaveValue('Saved category description');
  await expect(dialog.locator('input').nth(2)).toHaveValue('/images/manjha/m02.png');
  await expect(dialog.getByLabel('Active', { exact: true })).not.toBeChecked();
  await dialog.getByLabel('Active', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const cats = await (await page.request.get('/api/admin?res=categories')).json();
  const category = cats.categories.find((c: { name: string }) => c.name === 'Persistence category');

  await tab('Products');
  await page.getByRole('button', { name: 'Add Product', exact: true }).click();
  dialog = modal('Save Product');
  const values = ['Persistence product', '2345', '3000', 'PERSIST-E2E', '17', 'Persistence brand', '12'];
  for (const [index, value] of values.entries()) await dialog.locator('input').nth(index).fill(value);
  await dialog.locator('select').nth(0).selectOption(category.id);
  await dialog.locator('select').nth(1).selectOption('out_of_stock');
  await dialog.getByLabel('Image URLs (one per line)').fill('/images/manjha/m02.png');
  await dialog.locator('textarea').last().fill('Saved product description');
  await dialog.getByLabel('Featured', { exact: true }).check();
  await dialog.getByLabel('Bestseller', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Save Product', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await reloadTab('Products');
  const row = page.getByRole('row').filter({ hasText: 'PERSIST-E2E' });
  await row.getByRole('button').first().click();
  dialog = modal('Save Product');
  for (const [index, value] of values.entries()) await expect(dialog.locator('input').nth(index)).toHaveValue(value);
  await expect(dialog.locator('select').nth(0)).toHaveValue(category.id);
  await expect(dialog.locator('select').nth(1)).toHaveValue('out_of_stock');
  await expect(dialog.locator('textarea').last()).toHaveValue('Saved product description');
  await expect(dialog.getByLabel('Featured', { exact: true })).toBeChecked();
  await expect(dialog.getByLabel('Bestseller', { exact: true })).toBeChecked();
  await dialog.locator('input').nth(0).fill('Updated persistence product');
  await dialog.getByLabel('Active', { exact: true }).uncheck();
  await page.route('**/api/admin', route => route.fulfill({ status: 500, json: { ok: false, error: 'Database write failed' } }));
  await dialog.getByRole('button', { name: 'Save Product', exact: true }).click();
  await expect(page.getByText('Database write failed', { exact: true })).toBeVisible();
  await expect(dialog).toBeVisible();
  const before = await (await page.request.get('/api/admin?res=products')).json();
  expect(before.products.find((p: { sku: string }) => p.sku === 'PERSIST-E2E')).toMatchObject({ name: 'Persistence product', active: true });
  await page.unroute('**/api/admin');
  await dialog.getByRole('button', { name: 'Save Product', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await reloadTab('Products');
  const product = (await (await page.request.get('/api/admin?res=products')).json()).products.find((p: { sku: string }) => p.sku === 'PERSIST-E2E');
  expect(product).toMatchObject({ name: 'Updated persistence product', active: false, price: 2345, categoryId: category.id });
  expect((await (await page.request.get('/api/products?q=Updated%20persistence')).json()).products).toHaveLength(0);

  await tab('Customers');
  const buyerRow = page.getByRole('row').filter({ hasText: '9000000102' });
  await buyerRow.getByRole('button', { name: 'Disable', exact: true }).click();
  await expect(buyerRow.getByRole('button', { name: 'Enable', exact: true })).toBeVisible();
  await reloadTab('Customers');
  await expect(buyerRow.getByRole('button', { name: 'Enable', exact: true })).toBeVisible();
  await buyerRow.getByRole('button', { name: 'Enable', exact: true }).click();
  await expect(buyerRow.getByRole('button', { name: 'Disable', exact: true })).toBeVisible();

  await tab('Orders');
  await page.getByRole('row').filter({ hasText: 'E2E-023' }).click();
  await page.locator('select:visible').nth(0).selectOption('out_for_delivery');
  await page.locator('select:visible').nth(1).selectOption('refunded');
  await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
  await expect(page.getByText('Order updated — customer tracking reflects it', { exact: true })).toBeVisible();
  await reloadTab('Orders');
  await page.getByRole('row').filter({ hasText: 'E2E-023' }).click();
  await expect(page.locator('select:visible').nth(0)).toHaveValue('out_for_delivery');
  await expect(page.locator('select:visible').nth(1)).toHaveValue('refunded');

  await tab('Products');
  page.once('dialog', prompt => prompt.accept());
  await row.getByRole('button').last().click();
  await expect(row).toHaveCount(0);
  await reloadTab('Products');
  await expect(row).toHaveCount(0);
  await tab('Categories');
  page.once('dialog', prompt => prompt.accept());
  await categoryCard.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(categoryCard).toHaveCount(0);
  await reloadTab('Categories');
  await expect(categoryCard).toHaveCount(0);
});
