import { test, expect } from '@playwright/test';
const password = 'E2e-only-password-2026';
test('admin → delivery staff → customer, with responsive layout and access controls', async ({ page, browser }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/delivery');
  await expect(page).toHaveURL(/\/delivery\/login/);
  await page.goto('/admin/login');
  await page.getByLabel('Admin ID', { exact: true }).filter({ visible: true }).fill('e2eadmin');
  await page.getByLabel('Password', { exact: true }).filter({ visible: true }).fill(password);
  await page.getByRole('button', { name: 'Login to Dashboard' }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto('/admin/delivery');
  await expect(page.getByRole('heading', { name: 'Staff & couriers', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Courier Shipments' })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Shipment results' })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Shipment summary' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Open Next.js Dev Tools', exact: true })).toHaveCount(0);
  await page.getByLabel('Courier name', { exact: true }).filter({ visible: true }).fill('Manual Courier');
  await page.getByLabel('Official HTTPS tracking URL').filter({ visible: true }).fill('https://www.delhivery.com/track');
  await page.getByRole('button', { name: 'Save provider' }).click();
  await expect(page.getByText('Courier provider saved.')).toBeVisible();
  await page.getByLabel('Staff name', { exact: true }).filter({ visible: true }).fill('Delivery Operator');
  await page.getByLabel('Staff mobile number').filter({ visible: true }).fill('9000000104');
  await page.getByLabel('Password (at least 12 characters)', { exact: true }).filter({ visible: true }).fill(password);
  // Reproduce a session expiring while an admin is completing the form.
  await page.context().clearCookies();
  await page.getByRole('button', { name: 'Create delivery staff' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByLabel('Admin ID', { exact: true }).filter({ visible: true }).fill('e2eadmin');
  await page.getByLabel('Admin password', { exact: true }).filter({ visible: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in and retry' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('Staff access saved.')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Manage Delivery Operator' })).toBeVisible();
  await page.screenshot({ path: 'test-results/admin-settings.png', fullPage: true });
  await page.goto('/delivery');
  await expect(page.getByRole('heading', { name: '23 shipments', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Main admin', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.getByText('Page 2 of 2')).toBeVisible();
  await page.getByRole('button', { name: 'Previous', exact: true }).click();
  await page.getByLabel('Search shipments').filter({ visible: true }).fill('E2E-001');
  await page.getByRole('button', { name: 'Search & filter' }).click();
  await expect(page.getByRole('heading', { name: '1 shipments', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit courier', exact: true }).filter({ visible: true }).click();
  await page.getByLabel('Assigned delivery staff').filter({ visible: true }).selectOption({ label: 'Delivery Operator' });
  await page.getByRole('button', { name: 'Save Changes' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true });

  const staffContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const staffPage = await staffContext.newPage();
  staffPage.on('pageerror', e => errors.push(e.message));
  await staffPage.goto('/delivery/login');
  await staffPage.getByLabel('Mobile number').filter({ visible: true }).fill('9000000104');
  await staffPage.getByLabel('Password', { exact: true }).filter({ visible: true }).fill(password);
  await staffPage.getByRole('button', { name: 'Sign in to deliveries' }).click();
  await expect(staffPage.getByRole('heading', { name: '1 shipments', exact: true })).toBeVisible();
  await expect(staffPage.getByRole('button', { name: 'Staff & couriers' })).toHaveCount(0);
  await staffPage.getByRole('button', { name: 'Edit courier', exact: true }).filter({ visible: true }).click();
  await expect(staffPage.getByLabel('Assigned delivery staff').filter({ visible: true })).toHaveCount(0);
  await staffPage.getByLabel('Search courier companies').filter({ visible: true }).fill('Manual');
  await staffPage.getByLabel('Courier company', { exact: true }).filter({ visible: true }).selectOption({ label: 'Manual Courier' });
  await staffPage.getByLabel('Docket / AWB number').filter({ visible: true }).fill('AWB-E2E-001');
  await staffPage.getByLabel('Courier tracking URL').filter({ visible: true }).fill('https://www.delhivery.com/track/AWB-E2E-001');
  await staffPage.getByRole('dialog').getByLabel('Shipment status').filter({ visible: true }).selectOption('ASSIGNED');
  await staffPage.getByLabel('Internal delivery notes').filter({ visible: true }).fill('Private warehouse note');
  await staffPage.screenshot({ path: 'test-results/editor-mobile.png', fullPage: true });
  await staffPage.getByRole('button', { name: 'Save Changes' }).click();
  await expect(staffPage.getByRole('dialog')).not.toBeVisible();
  await staffPage.reload();
  await expect(staffPage.getByText('Manual Courier · AWB-E2E-001', { exact: true })).toBeVisible();
  await staffPage.screenshot({ path: 'test-results/staff-mobile.png', fullPage: true });
  expect(await staffPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  for (const status of ['PICKUP_PENDING', 'PICKED_UP', 'IN_TRANSIT']) {
    await staffPage.getByRole('button', { name: 'Edit courier', exact: true }).filter({ visible: true }).click();
    await staffPage.getByRole('dialog').getByLabel('Shipment status').filter({ visible: true }).selectOption(status);
    await staffPage.getByRole('button', { name: 'Save Changes' }).click();
    await expect(staffPage.getByRole('dialog')).not.toBeVisible();
    await expect(staffPage.getByText('Courier details saved. Customer tracking is up to date.', { exact: true })).toBeVisible();
  }
  await staffPage.reload();
  await expect(staffPage.getByRole('article').getByText('In transit', { exact: true })).toBeVisible();
  const persisted = await (await staffContext.request.get('/api/delivery/shipments')).json();
  expect(persisted.rows[0].status).toBe('IN_TRANSIT');
  expect(persisted.rows[0].docketNumber).toBe('AWB-E2E-001');
  expect(persisted.rows[0].trackingUrl).toBe('https://www.delhivery.com/track/AWB-E2E-001');
  expect((await staffContext.request.get('/api/admin')).status()).toBe(403);
  const denied = await staffContext.request.get('/admin');
  expect(denied.url()).toContain('/admin/login');
  expect((await staffContext.request.post('/api/payment/create', { data: {} })).status()).toBe(403);
  const customerContext = await browser.newContext();
  expect((await customerContext.request.post('/api/auth', { data: { action: 'login', phone: '9000000102', password } })).ok()).toBe(true);
  const customerPage = await customerContext.newPage();
  customerPage.on('pageerror', e => errors.push(e.message));
  await customerPage.goto('/track-order?num=E2E-001');
  await customerPage.getByRole('button', { name: 'Track', exact: true }).click();
  await expect(customerPage.getByRole('region', { name: 'Shipment tracking' })).toContainText('In transit');
  await expect(customerPage.getByRole('link', { name: 'Open courier tracking' })).toHaveAttribute('href', 'https://www.delhivery.com/track/AWB-E2E-001');
  await expect(customerPage.getByText('Private warehouse note')).toHaveCount(0);
  await expect(customerPage.getByText('Delivery Operator')).toHaveCount(0);
  await customerPage.screenshot({ path: 'test-results/customer-tracking.png', fullPage: true });
  await customerPage.goto('/delivery'); await expect(customerPage).toHaveURL(/\/delivery\/login/);
  const otherContext = await browser.newContext();
  await otherContext.request.post('/api/auth', { data: { action: 'login', phone: '9000000103', password } });
  expect((await otherContext.request.get('/api/orders/E2E-001')).status()).toBe(404);

  await page.goto('/admin/delivery');
  await page.getByRole('button', { name: 'Manage Delivery Operator' }).click();
  await page.getByLabel('Account active').filter({ visible: true }).uncheck();
  await page.getByRole('button', { name: 'Save staff access' }).click();
  await expect(page.getByText('Staff access saved.')).toBeVisible();
  expect((await staffContext.request.get('/api/delivery/shipments')).status()).toBe(403);
  await staffPage.reload(); await expect(staffPage).toHaveURL(/\/delivery\/login/);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete Delivery Operator' }).click();
  await expect(page.getByText('Delivery staff deleted. Shipment history preserved.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Manage Delivery Operator' })).toHaveCount(0);
  const afterDeletion = await (await customerContext.request.get('/api/orders/E2E-001')).json();
  expect(afterDeletion.order.shipment.status).toBe('IN_TRANSIT');
  expect(afterDeletion.order.shipment.docketNumber).toBe('AWB-E2E-001');
  expect(errors).toEqual([]);
  await staffContext.close(); await customerContext.close(); await otherContext.close();
});
